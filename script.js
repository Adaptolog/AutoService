        function getScrollContainer() {
            return document.getElementById('pageScroller');
        }

        function getObserverRoot() {
            return getScrollContainer() || null;
        }

        function setLang(lang) {
            const currentTranslations = translations[lang] || translations.uk;

            document.querySelectorAll('[data-key]').forEach((element) => {
                const key = element.getAttribute('data-key');
                const nextValue = currentTranslations[key];

                if (typeof nextValue === 'string') {
                    element.innerText = nextValue;
                }
            });

            document.querySelectorAll('.lang-switcher button').forEach((button) => {
                button.classList.remove('active');
            });

            const activeButton = document.getElementById(`btn-${lang}`);
            if (activeButton) {
                activeButton.classList.add('active');
            }
        }

        function setupRevealAnimations() {
            const animatedElements = document.querySelectorAll('.reveal, .reveal-item');
            const observerRoot = getObserverRoot();

            if (!animatedElements.length) {
                return;
            }

            if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
                animatedElements.forEach((element) => element.classList.add('is-visible'));
                return;
            }

            const observer = new IntersectionObserver((entries, currentObserver) => {
                entries.forEach((entry) => {
                    if (!entry.isIntersecting) {
                        return;
                    }

                    entry.target.classList.add('is-visible');
                    currentObserver.unobserve(entry.target);
                });
            }, {
                root: observerRoot,
                threshold: 0.18,
                rootMargin: '0px 0px -40px 0px'
            });

            animatedElements.forEach((element) => observer.observe(element));
        }

        function setupAboutCounters() {
            const counterElements = document.querySelectorAll('#about [data-count]');
            const aboutSection = document.getElementById('about');
            const observerRoot = getObserverRoot();

            if (!counterElements.length || !aboutSection) {
                return;
            }

            const setFinalValues = () => {
                counterElements.forEach((element) => {
                    const target = Number(element.getAttribute('data-count') || '0');
                    const suffix = element.getAttribute('data-suffix') || '';
                    element.textContent = `${target}${suffix}`;
                });
            };

            if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
                setFinalValues();
                return;
            }

            counterElements.forEach((element) => {
                const suffix = element.getAttribute('data-suffix') || '';
                element.textContent = `0${suffix}`;
            });

            let hasAnimated = false;

            const animateCounter = (element) => {
                const target = Number(element.getAttribute('data-count') || '0');
                const suffix = element.getAttribute('data-suffix') || '';
                const duration = 1300;
                const startTime = performance.now();

                const step = (currentTime) => {
                    const progress = Math.min((currentTime - startTime) / duration, 1);
                    const easedProgress = 1 - Math.pow(1 - progress, 3);
                    const value = Math.round(target * easedProgress);

                    element.textContent = `${value}${suffix}`;

                    if (progress < 1) {
                        window.requestAnimationFrame(step);
                    }
                };

                window.requestAnimationFrame(step);
            };

            const observer = new IntersectionObserver((entries, currentObserver) => {
                entries.forEach((entry) => {
                    if (!entry.isIntersecting || hasAnimated) {
                        return;
                    }

                    hasAnimated = true;
                    counterElements.forEach((element) => animateCounter(element));
                    currentObserver.unobserve(entry.target);
                });
            }, {
                root: observerRoot,
                threshold: 0.45
            });

            observer.observe(aboutSection);
        }

        function setupMobileNavigation() {
            const menuToggle = document.getElementById('menuToggle');
            const nav = document.getElementById('siteNav');
            const scrollContainer = getScrollContainer();

            if (!menuToggle || !nav) {
                return;
            }

            const closeMenu = () => {
                document.body.classList.remove('menu-open');
                menuToggle.setAttribute('aria-expanded', 'false');
                menuToggle.setAttribute('aria-label', 'Open navigation');
            };

            const openMenu = () => {
                document.body.classList.add('menu-open');
                menuToggle.setAttribute('aria-expanded', 'true');
                menuToggle.setAttribute('aria-label', 'Close navigation');
            };

            menuToggle.addEventListener('click', () => {
                if (document.body.classList.contains('menu-open')) {
                    closeMenu();
                    return;
                }

                openMenu();
            });

            nav.querySelectorAll('a').forEach((link) => {
                link.addEventListener('click', (event) => {
                    const targetSelector = link.getAttribute('href');
                    const targetElement = targetSelector ? document.querySelector(targetSelector) : null;

                    closeMenu();

                    if (!targetElement || !targetSelector.startsWith('#')) {
                        return;
                    }

                    event.preventDefault();
                    targetElement.scrollIntoView({ behavior: 'smooth', block: 'start' });

                    if (scrollContainer && window.innerWidth <= 768) {
                        history.replaceState(null, '', targetSelector);
                    }
                });
            });

            window.addEventListener('resize', () => {
                if (window.innerWidth > 768) {
                    closeMenu();
                }
            });
        }

        function setupActiveSectionTracking() {
            const navLinks = document.querySelectorAll('.nav-links a[href^="#"]');
            const observerRoot = getObserverRoot();
            const sections = Array.from(navLinks)
                .map((link) => document.querySelector(link.getAttribute('href')))
                .filter(Boolean);

            if (!navLinks.length || !sections.length) {
                return;
            }

            const observer = new IntersectionObserver((entries) => {
                entries.forEach((entry) => {
                    if (!entry.isIntersecting) {
                        return;
                    }

                    navLinks.forEach((link) => {
                        const isActive = link.getAttribute('href') === `#${entry.target.id}`;
                        link.classList.toggle('active-section', isActive);
                    });
                });
            }, {
                root: observerRoot,
                threshold: 0.55
            });

            sections.forEach((section) => observer.observe(section));
        }

        function setupHeroParallax() {
            const hero = document.getElementById('hero');
            const heroBg = document.getElementById('heroBg');
            const scrollContainer = getScrollContainer();

            if (!hero || !heroBg || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
                return;
            }

            let ticking = false;

            const updateParallax = () => {
                const heroRect = hero.getBoundingClientRect();
                const viewportHeight = window.innerHeight || document.documentElement.clientHeight;

                if (heroRect.bottom <= 0 || heroRect.top >= viewportHeight) {
                    ticking = false;
                    return;
                }

                const offset = scrollContainer
                    ? Math.max(scrollContainer.scrollTop, 0)
                    : Math.max(window.scrollY, 0);
                heroBg.style.transform = `translate3d(0, ${offset * 0.28}px, 0) scale(1.08)`;
                ticking = false;
            };

            const requestTick = () => {
                if (ticking) {
                    return;
                }

                ticking = true;
                window.requestAnimationFrame(updateParallax);
            };

            if (scrollContainer) {
                scrollContainer.addEventListener('scroll', requestTick, { passive: true });
            }

            window.addEventListener('scroll', requestTick, { passive: true });
            window.addEventListener('resize', requestTick);
            requestTick();
        }

        function setupDesktopWheelSnap() {
            const scrollContainer = getScrollContainer();

            if (!scrollContainer) {
                return;
            }

            const blockedKeys = new Set([
                'ArrowUp',
                'ArrowDown',
                'PageUp',
                'PageDown',
                'Home',
                'End',
                ' ',
                'Spacebar'
            ]);

            const isEditableTarget = (target) => {
                if (!(target instanceof HTMLElement)) {
                    return false;
                }

                return target.isContentEditable || ['INPUT', 'TEXTAREA', 'SELECT'].includes(target.tagName);
            };

            const sections = Array.from(scrollContainer.querySelectorAll(':scope > section'));

            if (!sections.length) {
                return;
            }

            let isAnimating = false;
            let lastWheelAt = 0;
            let wheelDeltaBuffer = 0;

            const getCurrentSectionIndex = () => {
                const currentTop = scrollContainer.scrollTop;
                let closestIndex = 0;
                let closestDistance = Number.POSITIVE_INFINITY;

                sections.forEach((section, index) => {
                    const distance = Math.abs(section.offsetTop - currentTop);

                    if (distance < closestDistance) {
                        closestDistance = distance;
                        closestIndex = index;
                    }
                });

                return closestIndex;
            };

            const scrollToSectionByIndex = (index) => {
                const targetSection = sections[index];

                if (!targetSection) {
                    return;
                }

                isAnimating = true;
                scrollContainer.scrollTo({ top: targetSection.offsetTop, behavior: 'smooth' });
                window.setTimeout(() => {
                    isAnimating = false;
                }, 700);
            };

            scrollContainer.addEventListener('wheel', (event) => {
                if (window.innerWidth < 1025) {
                    return;
                }

                event.preventDefault();

                if (isAnimating) {
                    return;
                }

                const now = Date.now();

                if (now - lastWheelAt > 220) {
                    wheelDeltaBuffer = 0;
                }

                lastWheelAt = now;
                wheelDeltaBuffer += event.deltaY;

                if (Math.abs(wheelDeltaBuffer) < 40) {
                    return;
                }

                const direction = wheelDeltaBuffer > 0 ? 1 : -1;
                const currentIndex = getCurrentSectionIndex();
                const nextIndex = Math.max(0, Math.min(sections.length - 1, currentIndex + direction));

                wheelDeltaBuffer = 0;

                if (nextIndex !== currentIndex) {
                    scrollToSectionByIndex(nextIndex);
                }
            }, { passive: false });

            document.addEventListener('keydown', (event) => {
                if (window.innerWidth < 1025 || isEditableTarget(event.target) || !blockedKeys.has(event.key)) {
                    return;
                }

                event.preventDefault();
            });
        }

        function hideLoadingScreen() {
            const loadingScreen = document.getElementById('loading-screen');

            if (!loadingScreen) {
                return;
            }

            loadingScreen.classList.add('hide');
        }

        document.addEventListener('DOMContentLoaded', () => {
            const userLang = navigator.language.substring(0, 2);
            const defaultLang = translations[userLang] ? userLang : 'uk';

            setLang(defaultLang);
            setupMobileNavigation();
            setupActiveSectionTracking();
            setupRevealAnimations();
            setupAboutCounters();
            setupHeroParallax();
            setupDesktopWheelSnap();

            const img = new Image();
            img.src = 'images/background.jpg';
            img.onload = hideLoadingScreen;
            img.onerror = hideLoadingScreen;
        });